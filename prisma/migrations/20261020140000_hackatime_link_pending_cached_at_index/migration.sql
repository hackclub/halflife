-- The Hackatime sync job runs every 15 minutes and reads the links it still
-- has to refresh: every row whose hours no reviewer has approved, least
-- recently refreshed first, the never-refreshed ones before the rest. There
-- was no index on either column, so every run scanned the whole table and
-- sorted it - and the run happens four times an hour.
--
-- The index is partial on the exact predicate the job filters by, so it holds
-- only the rows the job is about to read. NULLS FIRST matches the order the
-- job asks for: the default ASC order puts nulls last, which would put the
-- never-refreshed links at the end of the list, so the index supplies the
-- ordering and the run reads the rows it takes rather than the whole table.
CREATE INDEX "hackatime_link_cachedAt_idx" ON "hackatime_link"("cachedAt" NULLS FIRST) WHERE ("hoursApproved" IS NULL);
