import "server-only"
import { Phase } from "@/app/generated/prisma/enums"
import { projectUrl } from "@/lib/app-url"
import type { FileUpdate } from "@/lib/forge-write"

/**
 * A project's devlog, rendered as markdown that lands in the maker's repository, and its parts list as the CSV a spreadsheet expects.
 *
 * These files are GENERATED, and regenerated whole on every sync rather than appended to. That is what makes the sync idempotent: the repo's copy is a projection of what the platform holds, so a corrected entry fixes the file instead of leaving the old text above a correction, a deleted entry leaves no orphan behind, and a retried sync produces no diff at all.
 *
 * "No diff at all" is load-bearing, not a nicety: the write is skipped when the rendered bytes match the blob already in the repo (see `newestOf`), so the debounced after-write sync does not commit on every keystroke-save – only when something a reader would see actually changed.
 *
 * The banner at the top of each file says so, in the file, because the first thing a maker will do is edit it by hand. It is their repo; the note tells them the edit will be overwritten on the next sync rather than letting them discover it.
 */

/** The two paths the sync owns, relative to the repo root. */
export const JOURNAL_PATH = "JOURNAL.md"
export const BOM_PATH = "BOM.csv"
/**
 * Where the BOM lived before it became a CSV.
 *
 * Kept as a deletion in every sync rather than a one-off migration: a delete for a path that is not there is a no-op, so there is no state to track and no window in which a repo ends up with two BOMs. Removed once no synced repo can still carry it.
 */
export const LEGACY_BOM_PATH = "BOM.md"

/** The standing deletion of the old BOM path, for the sync's file set. */
export function legacyBomDeletion(): FileUpdate {
	return { path: LEGACY_BOM_PATH, content: null }
}

const BANNER = (what: string, projectId: string, generatedAt: Date, link: string) =>
	`<!-- Generated by Half Life from project ${projectId}. Edits here are overwritten on the next sync. -->\n` +
	`<!-- Generated: ${generatedAt.toISOString()} -->\n\n` +
	// The product link stays hard-coded to the real site – it names the platform, not this deployment – while the project link follows the resolved origin, so a checkout syncing locally still links the project it actually wrote to.
	`> [!NOTE]\n> This ${what} is mirrored from [Half Life](https://halflife.hackclub.com) – [open the project](${link}). ` +
	`Editing it here will not change the platform's copy, and the next sync overwrites this file.\n`

export type JournalEntry = {
	id: string
	phase: Phase
	title: string
	/** Rich text off a journal entry; tags are stripped before it lands here. */
	content: string | null
	hoursClaimed: number
	hoursApproved: number | null
	/** YYYY-MM-DD in the program timezone, as the journal stamped it. */
	effectiveDate: string | null
	createdAt: Date
	/** Playback links for the entry's timelapses, in order. */
	timelapses: { url: string | null }[]
}

/**
 * Whether an entry belongs where it does: DESIGN weeks read as designing, BUILD weeks as building. Used for the heading, not for filtering – every entry is written either way.
 */
const phaseWord = (phase: Phase) => (phase === Phase.DESIGN ? "Design" : "Build")

/** `1,234.5h` – the journal's own rounding, so the file matches the page. */
function hours(n: number): string {
	const rounded = Math.round(n * 100) / 100
	return `${rounded}h`
}

function dateOf(entry: JournalEntry): string {
	return entry.effectiveDate ?? entry.createdAt.toISOString().slice(0, 10)
}

/** A markdown heading slug: `What broke?` -> `what-broke`. */
function slug(text: string): string {
	return text
		.toLowerCase()
		.replace(/[^a-z0-9\s-]/g, "")
		.trim()
		.replace(/\s+/g, "-")
		.slice(0, 60)
}

/**
 * Rich journal HTML, cut down to markdown.
 *
 * The stored content is sanitised HTML (headings, lists, images, links, bold). Rather than ship an HTML-to-markdown dependency for one integration, the tags that matter are mapped and everything else is stripped to its text: an entry with a paragraph and a photo keeps both, and an entry using a tag nothing here knows about keeps its words. Images are left as their markdown form so a README-style render on GitHub shows the picture.
 */
function htmlToMarkdown(html: string): string {
	const mapped = html
		// Block ends become line breaks first, so a <p>a</p><p>b</p> does not run the two together.
		.replace(/<\/(p|div|h[1-6]|li|blockquote)>/gi, "\n\n")
		.replace(/<br\s*\/?>/gi, "\n")
		// Headings: GitHub renders `###` and is indifferent to which level was stored, so the entry's own hierarchy is kept.
		.replace(
			/<h([1-6])[^>]*>(.*?)<\/h\1>/gis,
			(_m, level: string, inner: string) => `${"#".repeat(Number(level))} ${inner.trim()}\n\n`,
		)
		// Images before links: an <a> wrapping an <img> would otherwise swallow it.
		.replace(/<img[^>]*?src=["']([^"']+)["'][^>]*?alt=["']([^"']*)["'][^>]*>/gi, "![$2]($1)")
		.replace(/<img[^>]*?alt=["']([^"']*)["'][^>]*?src=["']([^"']+)["'][^>]*>/gi, "![$1]($2)")
		.replace(/<img[^>]*?src=["']([^"']+)["'][^>]*>/gi, "![]($1)")
		.replace(/<a[^>]*?href=["']([^"']+)["'][^>]*>(.*?)<\/a>/gis, "[$2]($1)")
		.replace(/<(strong|b)>(.*?)<\/\1>/gis, "**$2**")
		.replace(/<(em|i)>(.*?)<\/\1>/gis, "_$2_")
		.replace(/<code>(.*?)<\/code>/gis, "`$1`")
		.replace(/<li[^>]*>/gi, "- ")

	// Tags left over by the mappings above are stripped to a fixed point: deleting one match can, in general, make the text on either side join into a new tag, so a single pass is not a complete sanitizer (`js/incomplete-multi-character-sanitization`). Repeat until the string stops changing; each pass that does anything removes at least `<x>`, so it always terminates.
	let text = mapped
	let previous = ""
	do {
		previous = text
		text = text.replace(/<[^>]+>/g, "")
	} while (text !== previous)

	return decodeEntities(text)
		.replace(/[ \t]+\n/g, "\n")
		.replace(/\n{3,}/g, "\n\n")
		.trim()
}

function decodeEntities(text: string): string {
	// `&amp;` is unescaped LAST. Decoding it first would turn the literal text `&amp;lt;` into `&lt;` and then into `<` in the same pass – unescaping twice, so text the author escaped once came out as live markup. Every other entity above must also run before this one for the same reason.
	return text
		.replace(/&nbsp;/g, " ")
		.replace(/&lt;/g, "<")
		.replace(/&gt;/g, ">")
		.replace(/&quot;/g, '"')
		.replace(/&#0?39;/g, "'")
		.replace(/&amp;/g, "&")
}

/** A table row, keeping empty cells rather than dropping the column. */
function row(...cells: (string | number | null | undefined)[]): string {
	return `| ${cells.map(c => (c === null || c === undefined || c === "" ? "—" : String(c))).join(" | ")} |`
}

/**
 * One CSV cell, quoted only when it has to be.
 *
 * The quoting is not cosmetic. A parts link is a query string, and those are full of commas – unquoted, a link lets a seventh cell into the row and every spreadsheet mis-parses it. So a cell holding a comma, a quote or a newline is wrapped and its quotes doubled, per RFC 4180.
 */
function cell(value: string | number): string {
	const text = String(value)
	if (/[",\r\n]/.test(text)) return `"${text.replace(/"/g, '""')}"`
	return text
}

function csvRow(cells: (string | number)[]): string {
	return cells.map(cell).join(",")
}

/** `$12.30` – dollars, two places, the way the BOM page shows them. */
function usd(n: number): string {
	return `$${n.toFixed(2)}`
}

/**
 * The newest moment the file's own content describes. The banner stamps this rather than the wall clock, because the wall clock is the one thing that always changes: with it, two syncs of identical content produced different bytes, so the blob SHA never matched, and the "skip unchanged files" guard in commitFiles never fired. Every debounced sync then wrote a commit with no diff.
 *
 * Only the file's own content counts – deliberately not the project row's `updatedAt`, which the sync itself writes `repoSyncedAt` to on every run. With that in the mix each sync moved its own date forward, so the file always looked changed and the guard still never fired. Date from the data, and a no-op sync is byte-identical.
 */
function newestOf(dates: Date[]): Date {
	return dates.reduce((a, b) => (b.getTime() > a.getTime() ? b : a), new Date(0))
}

/**
 * What a renderer returns: a file to write, never a deletion. Deletions only enter the sync's file set as explicit entries (see `legacyBomDeletion`), so narrowing here keeps every `.content` read below null-safe without assertions.
 */
export type RenderedFile = {
	path: string
	content: string
}

export type ProjectMeta = {
	id: string
	title: string
	description: string | null
	/** The program week the project's DESIGN phase runs in, or 0 for a warm-up. */
	weekId: number
	isWarmup: boolean
	themeLabel: string
	tier: number
	/** The link the maker gave for the repo itself, written into the header. */
	repoUrl: string | null
}

/**
 * JOURNAL.md: every devlog entry, grouped by phase and ordered oldest-first so the file reads as the project's story rather than its most recent news.
 */
export function renderJournal(project: ProjectMeta, entries: JournalEntry[]): RenderedFile {
	const lines: string[] = []
	lines.push(`# ${project.title} – devlog`, "")
	lines.push(
		BANNER("devlog", project.id, newestOf(entries.map(e => e.createdAt)), projectUrl(project.id)).trimEnd(),
		"",
	)
	if (project.description) lines.push(`> ${project.description.replace(/\n+/g, " ")}`, "")
	lines.push(
		row("Week", "Tier", "Hours logged", "Entries"),
		"| --- | --- | --- | --- |",
		row(
			project.isWarmup ? "Warm-up" : `Week ${project.weekId}`,
			`Tier ${project.tier}`,
			hours(entries.reduce((n, e) => n + (e.hoursApproved ?? e.hoursClaimed), 0)),
			entries.length,
		),
		"",
	)

	if (entries.length === 0) {
		lines.push("_No entries logged yet._", "")
		return { path: JOURNAL_PATH, content: lines.join("\n") }
	}

	// Oldest first: a devlog is read forward.
	const ordered = [...entries].sort((a, b) => a.createdAt.getTime() - b.createdAt.getTime())

	// A contents list, because a build week can be dozens of entries and GitHub's rendering has no sidebar.
	lines.push("## Contents", "")
	for (const [i, entry] of ordered.entries()) {
		lines.push(`${i + 1}. [${dateOf(entry)} – ${entry.title}](#${slug(`${dateOf(entry)} ${entry.title}`)})`)
	}
	lines.push("")

	let lastPhase: Phase | null = null
	for (const entry of ordered) {
		if (entry.phase !== lastPhase) {
			lines.push(`## ${phaseWord(entry.phase)}`, "")
			lastPhase = entry.phase
		}
		lines.push(`### ${dateOf(entry)} – ${entry.title}`, "")
		const claimed = entry.hoursApproved ?? entry.hoursClaimed
		const adjusted = entry.hoursApproved !== null && entry.hoursApproved !== entry.hoursClaimed
		lines.push(
			`**${hours(claimed)}**${adjusted ? ` _(${hours(entry.hoursClaimed)} logged, adjusted by a reviewer)_` : ""}`,
			"",
		)
		if (entry.content) lines.push(htmlToMarkdown(entry.content), "")
		for (const clip of entry.timelapses) if (clip.url) lines.push(`[Timelapse](${clip.url})`, "")
	}

	return { path: JOURNAL_PATH, content: lines.join("\n") }
}

export type BomLineForFile = {
	name: string
	purpose: string | null
	quantity: number
	unitCostUsd: number
	vendor: string | null
	link: string | null
	/** When the line last changed; dates the file, so a parts edit moves it. */
	updatedAt: Date
}

/**
 * BOM.csv: the parts list, one row per item, in the shape a spreadsheet or a parts calculator expects.
 *
 * CSV rather than markdown because this file is machine-read far more than it is read: it is what someone opens to price the build, sort by cost, or paste into a supplier. The columns follow that use – `Item, Qty, Supplier, Cost/item, Total Cost, link`.
 *
 * Two things that shape it, both deliberate:
 *
 * - **No totals row.** The shipping is a line item, not a footer, so the `Total Cost` column sums to the real total. A footer row would be counted a second time by anyone who sums the column, which is the whole point of the shape.
 * - **No generated banner.** A CSV is parsed by a machine that quacks at a stray comment row – it would arrive as a first cell containing `<!-- Generated by ... -->`. The banner is dropped rather than allowed to corrupt the file; JOURNAL.md still carries it. The path itself is the contract for the file being generated.
 */
export function renderBom(items: BomLineForFile[], taxShippingUsd: number): RenderedFile {
	const csv: string[] = []
	csv.push(csvRow(["Item", "Qty", "Supplier", "Cost/item", "Total Cost", "link"]))
	for (const item of items) {
		csv.push(
			csvRow([
				item.name,
				item.quantity,
				// Empty, not the markdown's em dash: an empty cell reads as "not stated" to a spreadsheet, while a dash is a value it will try to sort.
				item.vendor ?? "",
				usd(item.unitCostUsd),
				usd(item.quantity * item.unitCostUsd),
				item.link ?? "",
			]),
		)
	}
	csv.push(csvRow(["Estimated total shipping", 1, "", "", usd(taxShippingUsd), ""]))
	return { path: BOM_PATH, content: `${csv.join("\n")}\n` }
}
